#!/usr/bin/env python3
"""Rebuild everything that is generated from the week folders.

    python3 scripts/build.py          # indexes + README schedule + site/
    python3 scripts/build.py --no-site

Reads weeks/week-NN/{README.md, session-N.md, group-coaching.md} and writes:
  indexes/cue-words.md, videos.md, drills.md, coaching-principles.md, field-coaching.md
  the schedule table inside README.md (between the SCHEDULE markers)
  site/  (plain HTML copy of every page; needs `pip install markdown`)
"""
import re, sys, pathlib, collections, html

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEEKS = ROOT / 'weeks'
IDX = ROOT / 'indexes'
SPORT_ORDER = ['Baseball', 'Soccer', 'Flag Football', 'Athleticism', 'Mixed Backyard Day']
TYPE_ORDER = ['Warm-up', 'Skill Work', 'Game', 'Cool-down']
ACT_RE = re.compile(r'^## (Warm-up|Skill Work [A-Z]|Game|Cool-down): (.+?) \((\d+) min\) · Cue: \*\*(.+?)\*\*\s*$')
VID_RE = re.compile(r'🎥 \*\*Video:\*\* \[(.+?)\]\((https?://[^)]+)\) · \*Verified title: "(.+?)" \((.+?)\)\.\*\s*(.*)$')
SESS_RE = re.compile(r'^# Week (\d+) · Session (\d+): (.+?): (.+?) \((\d+) min\)\s*$')


def slug(text):
    """GitHub-style heading anchor."""
    text = re.sub(r'<[^>]+>', '', text).strip().lower()
    text = re.sub(r'[^\w\- ]', '', text, flags=re.UNICODE)
    return text.replace(' ', '-')


def load():
    weeks = []
    for wdir in sorted(WEEKS.glob('week-*')):
        wnum = int(wdir.name.split('-')[1])
        readme = (wdir / 'README.md').read_text()
        title = readme.splitlines()[0].lstrip('# ').strip()
        m = re.search(r'\*\*Week of ([^·*]+?)\s*·', readme)
        w = dict(num=wnum, dir=wdir, rel=f'weeks/{wdir.name}', title=title,
                 week_of=re.sub(r'^\w+day,\s*', '', m.group(1).strip()) if m else '', summary='SUMMARY ONLY' in title,
                 readme=readme, sessions=[], topics=[], meanings={})
        # cue meanings from the week's cheat sheet, if present
        for row in re.findall(r'^\| \*\*(.+?)\*\* \| .+? \| "?(.+?)"? \|$', readme, re.M):
            w['meanings'][row[0]] = row[1]
        for sf in sorted(wdir.glob('session-*.md'), key=lambda p: int(re.findall(r'\d+', p.name)[0])):
            lines = sf.read_text().splitlines()
            sm = SESS_RE.match(lines[0])
            if not sm:
                print(f'warning: {sf} has an unexpected title line', file=sys.stderr)
                continue
            s = dict(num=int(sm.group(2)), sport=sm.group(3), name=sm.group(4), minutes=sm.group(5),
                     file=f'{w["rel"]}/{sf.name}', acts=[])
            act = None
            for ln in lines:
                am = ACT_RE.match(ln)
                if am:
                    act = dict(type=am.group(1), kind=am.group(1).split(' ')[0] if am.group(1).startswith('Skill') else am.group(1),
                               name=am.group(2), minutes=am.group(3), cue=am.group(4),
                               anchor=slug(ln[3:]), videos=[], why='')
                    if act['type'].startswith('Skill'):
                        act['kind'] = 'Skill Work'
                    s['acts'].append(act)
                    continue
                if act is None:
                    continue
                vm = VID_RE.search(ln)
                if vm:
                    act['videos'].append(dict(label=vm.group(1), url=vm.group(2), title=vm.group(3),
                                              channel=vm.group(4), note=vm.group(5)))
                if ln.startswith('- **Why it works:**'):
                    act['why'] = ln[len('- **Why it works:**'):].strip()
            w['sessions'].append(s)
        gc = wdir / 'group-coaching.md'
        if gc.exists():
            for ln in gc.read_text().splitlines():
                if ln.startswith('## '):
                    w['topics'].append(dict(name=ln[3:].strip(), anchor=slug(ln[3:]), file=f'{w["rel"]}/group-coaching.md'))
        weeks.append(w)
    return weeks


def link(text, path, anchor='', base='indexes'):
    rel = ('../' if base == 'indexes' else '') + path
    return f'[{text}]({rel}{"#" + anchor if anchor else ""})'


def sport_key(sp):
    return (SPORT_ORDER.index(sp) if sp in SPORT_ORDER else 99, sp)


HEADER = '<!-- Generated by scripts/build.py from the week folders. Edit the week files, then rerun the script. -->\n'


def summary_note(weeks):
    s = [w for w in weeks if w['summary']]
    if not s:
        return ''
    names = ' and '.join(link(f'Week {w["num"]}', w['rel'] + '/README.md') for w in s)
    return (f'> **Note:** {names} only have summary pages (the full plans were not recovered), '
            'so their drills, cue words and videos are not listed here.\n\n')


def build_cues(weeks):
    out = [HEADER, '# Cue Words (all weeks)', '', '[← Home](../README.md)', '',
           'One cue word per activity. Grouped by sport, alphabetical within each sport.', '', summary_note(weeks)]
    by = collections.defaultdict(list)
    for w in weeks:
        for s in w['sessions']:
            for a in s['acts']:
                by[s['sport']].append((a['cue'].lower(), w, s, a))
    for sp in sorted(by, key=sport_key):
        out += [f'## {sp}', '', '| Cue | Activity | Week / Session | What it means to the kid |', '|---|---|---|---|']
        for _, w, s, a in sorted(by[sp], key=lambda t: (t[0], t[1]['num'], t[2]['num'])):
            meaning = w['meanings'].get(a['cue'], '')
            meaning = f'"{meaning}"' if meaning else ''
            out.append(f'| **{a["cue"]}** | {link(a["type"] + ": " + a["name"], s["file"], a["anchor"])} | '
                       f'{link("W%d S%d" % (w["num"], s["num"]), s["file"])} | {meaning} |')
        out.append('')
    (IDX / 'cue-words.md').write_text('\n'.join(out))


def build_videos(weeks):
    out = [HEADER, '# Videos (all weeks)', '', '[← Home](../README.md)', '',
           'Every YouTube link in the plans, in week and session order. These are mostly for the coach to watch, not the boys.', '',
           summary_note(weeks), '| # | Video | Channel | Week / Session | Activity |', '|---|---|---|---|---|']
    i = 0
    for w in weeks:
        for s in w['sessions']:
            for a in s['acts']:
                for v in a['videos']:
                    i += 1
                    out.append(f'| {i} | [{v["title"].replace("|", chr(92) + "|")}]({v["url"]}) | {v["channel"]} | '
                               f'{link("W%d S%d: %s" % (w["num"], s["num"], s["sport"]), s["file"])} | '
                               f'{link(a["name"], s["file"], a["anchor"])} |')
    out.append('')
    (IDX / 'videos.md').write_text('\n'.join(out))


def build_drills(weeks):
    out = [HEADER, '# Drills & Games Catalog (all weeks)', '', '[← Home](../README.md)', '',
           'Grouped by sport, then by activity type (warm-up, skill work, game, cool-down).', '', summary_note(weeks)]
    by = collections.defaultdict(lambda: collections.defaultdict(list))
    for w in weeks:
        for s in w['sessions']:
            for a in s['acts']:
                by[s['sport']][a['kind']].append((w, s, a))
    for sp in sorted(by, key=sport_key):
        out += [f'## {sp}', '']
        for kind in TYPE_ORDER:
            items = by[sp].get(kind)
            if not items:
                continue
            out += [f'### {kind}', '', '| Drill / game | Cue | Min | Week / Session | Video |', '|---|---|---|---|---|']
            for w, s, a in items:
                vids = ', '.join(f'[{v["label"]}]({v["url"]})' for v in a['videos'])
                out.append(f'| {link(a["name"], s["file"], a["anchor"])} | **{a["cue"]}** | {a["minutes"]} | '
                           f'{link("W%d S%d: %s" % (w["num"], s["num"], s["name"]), s["file"])} | {vids} |')
            out.append('')
    (IDX / 'drills.md').write_text('\n'.join(out))


# Learning ideas named in bold inside the "Why it works" notes, normalised to one name each.
PRINCIPLES = [
    ('External focus', [r'external focus']),
    ('Analogy / implicit learning', [r'analogy learning', r'\bimplicitly\b', r'\*analogy\*']),
    ('Errorless learning (start easy, then add difficulty)', [r'errorless learning']),
    ('Constraints-led games (let the setup do the coaching)', [r'constraints-led', r'\bconstraint\b', r'constraint on the environment']),
    ('Whole-part-whole / part practice', [r'whole-part-whole', r'part-practice', r'part-to-whole', r'whole practice']),
    ('Contrast (show wrong vs. right)', [r'\bcontrast\b']),
    ('Progression from easy to hard', [r'progression from easy to hard']),
    ('Just-right challenge / scaling the task', [r'just-right challenge', r'scaling the task', r'60 to 80% success']),
    ('Autonomy (let them choose)', [r'\bautonomy\b']),
    ('Developmentally appropriate', [r'developmentally appropriate']),
    ('Cooperative motivation', [r'\bcooperative\b']),
    ('Variable practice', [r'variable practice']),
    ('Reaction training', [r'reaction trigger', r'reaction time']),
    ('Mental rehearsal', [r'mental rehearsal']),
]


def build_principles(weeks):
    out = [HEADER, '# Coaching Principles (how to teach)', '', '[← Home](../README.md)', '',
           'The general teaching habits used across the plans, quoted from the weekly plans, plus the learning ideas behind each drill (from its "Why it works" note).', '',
           summary_note(weeks)]
    for w in weeks:
        if w['summary']:
            continue
        r = w['readme']
        rules = re.search(r'(\*\*Three rules for the whole week:\*\*\n(?:\d\..*\n)+)', r)
        demo = re.search(r'(\*\*A quick note on the silent demo:\*\*.*)', r)
        if rules or demo:
            out += [f'## House rules (from {link("Week %d" % w["num"], w["rel"] + "/README.md")})', '']
            if rules:
                out += [rules.group(1).strip(), '']
            if demo:
                out += [demo.group(1).strip(), '']
        for t in w['topics']:
            if 'ask before tell' in t['name'].lower():
                out += [f'**Ask before tell:** see {link(t["name"], t["file"], t["anchor"])} in the Week {w["num"]} field-coaching notes.', '']
    out += ['## Learning ideas behind the drills', '',
            'Each idea links to every activity whose "Why it works" note names it, with the sentence that names it.', '']
    for name, pats in PRINCIPLES:
        rows = []
        for w in weeks:
            for s in w['sessions']:
                for a in s['acts']:
                    sentences = re.split(r'(?:(?<=[.!?])|(?<=[.!?]"))\s+(?=[A-Z*])', a['why'])
                    hit = next((x for x in sentences if any(re.search(p, x, re.I) for p in pats)), None)
                    if hit:
                        rows.append(f'- {link("W%d S%d · %s" % (w["num"], s["num"], a["name"]), s["file"], a["anchor"])}: {hit}')
        if rows:
            out += [f'### {name}', ''] + rows + ['']
    (IDX / 'coaching-principles.md').write_text('\n'.join(out))


def build_field(weeks):
    out = [HEADER, '# Field Coaching (group practice tips, all weeks)', '', '[← Home](../README.md)', '']
    for w in weeks:
        out += [f'## Week {w["num"]}', '']
        if w['topics']:
            for t in w['topics']:
                out.append(f'- {link(t["name"], t["file"], t["anchor"])}')
        elif w['summary']:
            out.append(f'- Full group-coaching section not recovered; see the {link("Week %d summary" % w["num"], w["rel"] + "/README.md")}.')
        out.append('')
    (IDX / 'field-coaching.md').write_text('\n'.join(out))


def build_schedule(weeks):
    days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun']
    plan = {'Mon': 1, 'Tue': 2, 'Thu': 3, 'Fri': 4, 'Sat': 5}
    rows = ['| Week | ' + ' | '.join(f'{d} {"S%d" % plan[d] if d in plan else ("Play" if d == "Wed" else "Rest")}' for d in days) + ' |',
            '|' + '---|' * 8]
    for w in weeks:
        label = link(f'Week {w["num"]}', w['rel'] + '/README.md', base='root')
        if w['week_of']:
            label += f'<br>{w["week_of"]}'
        if w['summary']:
            label += '<br>*(summary only)*'
        cells = []
        sess = {s['num']: s for s in w['sessions']}
        for d in days:
            if d == 'Wed':
                cells.append('10-min play')
            elif d == 'Sun':
                cells.append('Rest')
            elif plan[d] in sess:
                s = sess[plan[d]]
                cells.append(link(f'S{s["num"]} {s["sport"]}: {s["name"]}', s['file'], base='root'))
            else:
                cells.append('*not recovered*' if w['summary'] else '')
        rows.append(f'| {label} | ' + ' | '.join(cells) + ' |')
    readme = ROOT / 'README.md'
    t = readme.read_text()
    new = '<!-- SCHEDULE:START (generated by scripts/build.py) -->\n' + '\n'.join(rows) + '\n<!-- SCHEDULE:END -->'
    t = re.sub(r'<!-- SCHEDULE:START.*?<!-- SCHEDULE:END -->', new, t, flags=re.S)
    readme.write_text(t)


